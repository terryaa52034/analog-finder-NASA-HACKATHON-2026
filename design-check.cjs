const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({headless:true});
  try{
    const page=await browser.newPage({viewport:{width:1536,height:1000}}),errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.goto('http://127.0.0.1:8765');
    await page.locator('#intro-orbit').click();
    await page.waitForSelector('.intro-cosmos canvas');
    await page.waitForTimeout(1200);
    assert.equal(await page.locator('.intro-body-label').count(),3);
    assert.ok(await page.locator('[data-body-label=Earth]').isVisible());
    await page.screenshot({path:'analog-finder/design-intro.png'});
    assert.ok(await page.locator('.intro-guide agent-mascot').isVisible());
    await page.locator('#intro-enter').click();
    await page.locator('#mission-intro').waitFor({state:'hidden'});
    await page.waitForFunction(()=>!document.querySelector('#drone-open').disabled);
    await page.waitForTimeout(900);
    assert.equal(await page.locator('.intro-cosmos canvas').count(),0);
    assert.equal(await page.locator('.target[aria-checked=true]').count(),0);
    assert.equal(await page.locator('#results button').count(),0);
    assert.equal(await page.locator('#card').isVisible(),false);
    assert.ok(await page.locator('#drone-mission-card').isVisible());
    assert.ok(await page.locator('.country-label').count()>0);
    await page.screenshot({path:'analog-finder/design-dashboard.png'});
    await page.locator('.layer-dock summary').click();
    assert.match(await page.locator('.layer-checks').textContent(),/Country labels/);
    await page.selectOption('#overlay-layer','elev');
    assert.match(await page.locator('#legend-note').textContent(),/Altitude/);
    await page.locator('#show-labels').uncheck();assert.equal(await page.locator('.country-label').count(),0);
    await page.locator('#show-labels').check();
    await page.selectOption('#overlay-layer','match');assert.equal(await page.locator('.legend').isVisible(),false);
    const rect=await page.locator('#map').boundingBox();await page.locator('#map').click({position:{x:rect.width/2,y:rect.height/2}});
    await page.waitForSelector('#card:not([hidden])');assert.match(await page.locator('#card').textContent(),/EARTH REFERENCE/);
    await page.locator('.target').filter({hasText:'Jezero crater'}).click();
    assert.equal(await page.locator('#results button').count(),15);
    await page.locator('#intro-replay').click();await page.locator('#intro-orbit').click();await page.waitForSelector('.intro-cosmos canvas');
    await page.locator('#intro-drone').click();await page.waitForSelector('#drone-canvas canvas');
    assert.equal(await page.locator('#drone-explorer').getAttribute('data-body'),'Mars');
    await page.locator('#drone-close').click();
    assert.equal(await page.locator('#results button').count(),15);
    await page.setViewportSize({width:390,height:844});
    await page.locator('#card .close').click();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.screenshot({path:'analog-finder/design-mobile.png'});
    await page.locator('#intro-replay').click();await page.locator('#intro-orbit').click();await page.waitForSelector('.intro-cosmos canvas');
    await page.waitForTimeout(150);
    assert.ok(await page.locator('[data-body-label=Earth]').isVisible());
    await page.screenshot({path:'analog-finder/design-intro-mobile.png'});
    await page.locator('#intro-enter').click();
    assert.deepEqual(errors,[]);
    const accessible=await browser.newContext({reducedMotion:'reduce',viewport:{width:390,height:844}});
    const reduced=await accessible.newPage();await reduced.goto('http://127.0.0.1:8765');
    await reduced.locator('#intro-enter').click();await reduced.locator('#mission-intro').waitFor({state:'hidden'});
    assert.equal(await reduced.locator('.intro-cosmos canvas').count(),0);
    // No WebGL still offers a visible Earth and working mission actions.
    const fallback=await browser.newPage();
    await fallback.addInitScript(()=>{const original=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){return /webgl/i.test(type)?null:original.call(this,type,...args);};});
    await fallback.goto('http://127.0.0.1:8765');await fallback.locator('#intro-enter').click();await fallback.locator('#mission-intro').waitFor({state:'hidden'});
    await fallback.waitForSelector('#targets button');assert.equal(await fallback.locator('.target[aria-checked=true]').count(),0);
    console.log('PASS: animated intro, zoom handoff, LUMA, neutral target state, country labels, independent overlays, Earth reference, drone entry, replay, preserved state, mobile, reduced motion, and WebGL fallback.');
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1)});
