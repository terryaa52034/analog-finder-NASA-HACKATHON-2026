const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({headless:true});
  try {
    const page=await browser.newPage({viewport:{width:1536,height:1000},deviceScaleFactor:1.5});
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    await page.goto('http://127.0.0.1:8765');
    await page.locator('#intro-skip').click();
    await page.waitForFunction(()=>!document.querySelector('#drone-open').disabled);
    const modelChecks=await page.evaluate(async()=>{
      const {coordinatesAt,makeTerrain,analyseCapture}=await import('./drone-model.js');
      const {TARGETS}=await import('./targets.js');
      const origin={lat:18.4,lon:77.5},still=coordinatesAt('Mars',origin,0,0),north=coordinatesAt('Mars',origin,0,-100);
      const pole=coordinatesAt('Moon',{lat:90,lon:179.999},100,100);
      const seam=coordinatesAt('Mars',{lat:0,lon:179.999},100,0);
      const a=makeTerrain('Moon',origin),b=makeTerrain('Moon',origin);
      const session={body:'Moon',origin,target:TARGETS[0]},capture=analyseCapture(session,{x:100,z:-100,altitude:22},1);
      return {still,north,pole,seam,deterministic:a.height(11,18)===b.height(11,18),rough:capture.roughness,originalRelief:TARGETS[0].traits.rough.body,newRelief:capture.matchTarget.traits.rough.body,coordinates:capture.coordinates};
    });
    assert.equal(modelChecks.still.lat,18.4);assert.equal(modelChecks.still.lon,77.5);assert.ok(modelChecks.north.lat>18.4);
    assert.ok(Number.isFinite(modelChecks.pole.lat)&&Number.isFinite(modelChecks.pole.lon));assert.ok(modelChecks.seam.lon<0);
    assert.ok(modelChecks.deterministic&&modelChecks.rough>0);assert.notEqual(modelChecks.originalRelief,modelChecks.newRelief);
    await page.locator('#drone-open').click();
    await page.waitForSelector('#drone-canvas canvas');
    assert.equal(await page.locator('#drone-explorer').getAttribute('data-body'),'Moon');
    await page.locator('#drone-lat').fill('0.67');await page.locator('#drone-lon').fill('23.47');
    await page.locator('#drone-deploy').click();
    await page.waitForSelector('#drone-canvas canvas');
    assert.equal(await page.locator('#drone-capture').isDisabled(),true);
    await page.locator('#drone-launch').click();
    await page.waitForFunction(()=>!document.querySelector('#drone-capture').disabled);
    await page.keyboard.down('w');await page.waitForTimeout(1200);await page.keyboard.up('w');
    await page.locator('[data-move=d]').hover();await page.mouse.down();await page.waitForTimeout(500);await page.mouse.up();
    const moved=await page.locator('#drone-position').getAttribute('data-lat');assert.ok(Number(moved)>0.67,'Flight must change planetary latitude');
    await page.screenshot({path:'analog-finder/drone-moon.png'});
    for(const view of ['fpv','down','chase'])await page.locator(`[data-view=${view}]`).click();
    await page.locator('#drone-capture').click();
    await page.waitForSelector('.drone-captured-frame img');
    assert.match(await page.locator('#drone-capture-content').textContent(),/Moon/);
    const captureImage=await page.locator('.drone-captured-frame img').getAttribute('src');assert.ok(captureImage.length>10000,'Actual rendered capture required');
    assert.equal(await page.locator('#drone-history button').count(),1);
    await page.locator('#drone-return').click();
    await page.waitForFunction(()=>document.querySelector('#drone-flight-status').textContent==='Landed at base',{},{timeout:30000});
    await page.locator('#drone-match').click();
    await page.locator('#drone-explorer').waitFor({state:'hidden'});
    assert.equal(await page.locator('#results button').count(),10);
    assert.match(await page.locator('#drone-result-banner').textContent(),/Moon capture/);
    assert.ok(await page.locator('.capture-provenance').isVisible());
    await page.locator('#drone-open').click();await page.waitForSelector('#drone-canvas canvas');
    assert.equal(await page.locator('#drone-history button').count(),1);
    assert.equal(await page.locator('.drone-captured-frame img').getAttribute('src'),captureImage);
    await page.locator('[data-body=Mars]').click();await page.waitForSelector('#drone-canvas canvas');
    await page.selectOption('#drone-site','mars-jezero');await page.waitForSelector('#drone-canvas canvas');
    // A user-selected position on the planetary planner is the deployment anchor.
    await page.locator('#planet-planner').click({position:{x:130,y:40}});
    await page.waitForSelector('#drone-canvas canvas');
    const selectedLat=Number(await page.locator('#drone-lat').inputValue());
    await page.locator('#drone-launch').click();await page.waitForFunction(()=>!document.querySelector('#drone-capture').disabled);
    await page.screenshot({path:'analog-finder/drone-mars.png'});
    await page.locator('#drone-capture').click();
    const captureText=await page.locator('#drone-capture-content').textContent();
    assert.match(captureText,/Mars/);assert.match(captureText,new RegExp(selectedLat.toFixed(5).replace('.','\\.')));
    assert.equal(await page.locator('#drone-history button').count(),2);
    await page.locator('#drone-canvas canvas').focus();await page.keyboard.down('d');await page.waitForTimeout(600);await page.keyboard.up('d');
    await page.locator('#drone-return').click();
    await page.waitForFunction(()=>document.querySelector('#drone-flight-status').textContent==='Landed at base',{},{timeout:30000});
    await page.locator('#drone-match').click();await page.locator('#drone-explorer').waitFor({state:'hidden'});
    assert.equal(await page.locator('#drone-canvas canvas').count(),0,'Closing must release the scene canvas');
    assert.equal(await page.locator('#results button').count(),10);
    assert.match(await page.locator('#drone-result-banner').textContent(),/Mars capture/);
    await page.locator('#reset-weights').click();assert.equal(await page.locator('#results button').count(),10);
    await page.locator('.layer-dock summary').click();
    await page.selectOption('#overlay-layer','t_max');assert.match(await page.locator('#legend-note').textContent(),/Hottest/);
    await page.locator('.target').filter({hasText:'Mare Tranquillitatis'}).click();
    assert.equal(await page.locator('#results button').count(),15,'Regular Earth matching preserved');
    await page.locator('#drone-open').click();await page.waitForSelector('#drone-canvas canvas');
    assert.equal(await page.locator('#drone-history button').count(),2);
    await page.locator('#drone-lat').fill('91');await page.locator('#drone-deploy').click();
    assert.match(await page.locator('#drone-notice').textContent(),/latitude from/);
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.querySelector('#drone-explorer').scrollWidth>innerWidth),false);
    await page.screenshot({path:'analog-finder/drone-mobile.png'});
    await page.locator('#drone-match').scrollIntoViewIfNeeded();assert.ok(await page.locator('#drone-match').isVisible());
    await page.locator('#drone-close').scrollIntoViewIfNeeded();
    await page.locator('#drone-close').click();
    // Repeated open/close leaves one active canvas and releases it each time.
    for(let i=0;i<2;i++){await page.locator('#drone-open').click();await page.waitForSelector('#drone-canvas canvas');assert.equal(await page.locator('#drone-canvas canvas').count(),1);await page.locator('#drone-close').click();assert.equal(await page.locator('#drone-canvas canvas').count(),0);}
    await page.locator('#drone-open').click();await page.waitForSelector('#drone-canvas canvas');
    await page.locator('#drone-canvas canvas').dispatchEvent('webglcontextlost',{cancelable:true});
    assert.match(await page.locator('#drone-notice').textContent(),/graphics context was lost/);
    assert.equal(await page.locator('#drone-launch').isDisabled(),true);
    await page.locator('#drone-close').click();
    await page.locator('#drone-open').click();await page.waitForSelector('#drone-canvas canvas');assert.equal(await page.locator('#drone-history button').count(),2);await page.locator('#drone-close').click();
    assert.deepEqual(errors,[]);
    console.log('PASS: Moon/Mars launch, movement, cameras, capture, coordinates, return/landing, top-10 Earth matching, retained history, input validation, cleanup, mobile, and normal Earth search.');
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
